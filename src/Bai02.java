public class Bai02 {
    public static void main(String[] args) {
        // println => con trỏ nhảy xuống dưới dòng sau khi kết thúc
        System.out.println("dong 1"); // sout
        System.out.println("dong 2"); // sout
        System.out.println("dong 3"); // ctrl + D

        // print => con trỏ ở cuối chuỗi sau khi xuất xong
        System.out.print("dong 4");
        System.out.print("dong 5");
        System.out.println("");

        // \t => thụt vào 1 tab
        System.out.println("Cộng hòa xã hội chủ nghĩa Việt Nam");
        System.out.println("\tĐộc lập - Tự do - Hạnh phúc");

        // \n => enter xuống dòng
        System.out.println("Sông cầu nước chảy lơ thơ\nCố đôi trai gái ngồi hơ quần đùi");

        // dấu nháy "" => trong văn bản có dấu ""
        System.out.println("Có người nói rằng \"Cho đi là còn mãi\"");
    }
}